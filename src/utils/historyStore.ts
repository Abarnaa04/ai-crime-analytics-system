export const historyStore = {
  getHistory(): PredictionResult[] {
    try {
      const saved = localStorage.getItem(HISTORY_STORAGE_KEY);
      if (saved) return JSON.parse(saved);
    } catch {
      // ignore
    }
    localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify(DEFAULT_HISTORY));
    return DEFAULT_HISTORY;
  },

  addPrediction(pred: PredictionResult): void {
    const list = this.getHistory();
    list.unshift(pred);
    try {
      localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify(list));
    } catch {
      // ignore
    }
  },

  deletePrediction(id: string): void {
    const list = this.getHistory().filter(item => item.id !== id);
    try {
      localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify(list));
    } catch {
      // ignore
    }
  },

  updateNotes(id: string, notes: string): void {
    const list = this.getHistory();
    const item = list.find(i => i.id === id);
    if (item) {
      item.analystNotes = notes;
      localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify(list));
    }
  },

  clearHistory(): void {
    localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify([]));
  },
};
